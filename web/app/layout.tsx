import type { Metadata } from "next";
import { Space_Grotesk, Orbitron } from "next/font/google";
import "./globals.css";
import { gameQuery } from '@/sanity/queries';
import { cachedFetch } from '@/sanity/util';
import Nav from "@/components/Nav";
import Footer from "@/components/Footer";

const orbitron = Orbitron({
  variable: "--font-orbitron",
  subsets: ["latin"],
});

const spaceGrotesk = Space_Grotesk({
  variable: "--font-space-grotesk",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "TinkerBot",
  description: "Generated by create next app",
};

export default async function RootLayout({ children }: LayoutProps<"/">) {
  const games = await cachedFetch(gameQuery, {
    slug: null,
  });

  return (
    <html
      lang="en"
      className={`${spaceGrotesk.variable} ${orbitron.variable} antialiased`}
    >
      <body className="sky-background l min-h-full flex flex-col justify-center items-center p-6 lg:p-12 lg:pt-6">
        <div>
          <Nav games={games} />
          {children}
          <Footer />
        </div>
      </body>
    </html>
  );
}
